# Numbers -:

a = -23
b = 45
c = 56

# int - 0 to infinity and -1 to negative infinity
print(type(c))

# float - decimal and fraction number
d = 12.1
print(type(d))

#complex - imaginary number
e = 12 + 3j
print(type(e))

#String -: anything inside quotes- "" or ''

name = 'NYC'
print(type(name))
print(name)

#Boolean -: 

g = True
h = False

print(type(g))
print(type(h))

