# Dictionary -: keys and values -> print(dic[keys]) -> {key:value}
   # Vanila python -:

d = {10:100,20:200,30:300,40:400,50:500}       # 10,20,30,40 -> they are keys | 100,200,300,400 -> they are values of keys.
print(d[10])                     # 100

# creating a new key value pair -:

d[50] = 500
print(d)                         # {10:100,20:200,30:300,40:400,50:500}

